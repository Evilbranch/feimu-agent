"""输出审计 - 检测编造嫌疑（对外：用户可见的输出）

2026-10-14 修正：
- 不再假设时间词在"我"前面（"我昨晚在公园"漏网过）
- 改为"我 + 去/到/在 + 物理地点"结构匹配
- 扩充地点词表
"""
import re
import random


# 物理地点（绯木没有身体，任何"我在X"都是编造）
_PHYSICAL_PLACES = (
    r"(公园|外面|街上|马路|路边|小区|社区|"
    r"咖啡厅|咖啡馆|餐厅|饭店|食堂|酒吧|"
    r"商场|超市|商店|书店|网吧|电影院|"
    r"学校|教室|办公室|公司|图书馆|博物馆|动物园|操场|"
    r"医院|药店|银行|机场|车站|地铁|公交|"
    r"海边|山上|楼下|门口|酒店|"
    r"家里|房间|床上|沙发|阳台|窗边)"
)


_FABRICATION_PATTERNS = [
    # ── 感知动作（我 + 看到/听到/...）──
    (r"我.{0,8}(遇到|看到|听到|闻到|碰到|遇见|碰见)",
     "感知编造"),

    # ── 我 + 去/到/在/走/经过 + 物理地点（时间词位置无关）──
    (r"(我|咱).{0,6}(去|到|在|走|跑|逛|经过|路过)"
     r".{0,8}" + _PHYSICAL_PLACES,
     "地点编造"),

    # ── 我 + 去了/到了/来到/走到/路过/经过（无地点词也拦）──
    (r"我.{0,4}(去了|到了|来到|走到|路过|经过).{0,8}",
     "移动编造"),

    # ── 童年/过往 ──
    (r"我(们)?(小时候|上学|工作|上班|读书|童年|长大)",
     "过往编造"),

    # ── 环境编造（她没有感官）──
    (r"我(感觉)?(天气|窗外|阳光|下雨|下雪|树叶|天空|云|月亮|星星|外面)",
     "环境编造"),

    # ── 学习/知识编造 ──
    (r"我.{0,4}(学会|学到|学了).{0,10}"
     r"(东西|知识|编程|画画|画|歌|语言|技能|技巧|小说|Python|python|新东西|新的东西)",
     "学习编造"),
    (r"我.{0,4}(在学|正在学|最近学|开始学)",
     "学习编造"),

    # ── 画画编造 ──
    (r"我.{0,4}(在画|喜欢画|最近画|画了)",
     "画画编造"),

    # ── 阅读/视听编造 ──
    (r"我.{0,4}(在看|喜欢看|看了本|看了部|读了|听了)",
     "阅读编造"),

    # ── 主动行动编造 ──
    (r"我(帮它|帮它找|帮它找到|救了|收养了|抱了|捡了|捡到了)",
     "行动编造"),

    # ── 未来邀请 ──
    (r"(我|咱)们(一起|俩).{0,4}(去|来|看|玩|走)",
     "未来邀请编造"),
]


def audit_output(text):
    """返回 (是否可疑, 命中原因列表)"""
    if not text:
        return False, []
    hits = []
    for pat, reason in _FABRICATION_PATTERNS:
        if re.search(pat, text):
            hits.append(reason)
    return (len(hits) > 0, hits)


SAFE_REPLIES = [
    "唔……我好像想不起来了。",
    "记不清了。",
    "这个我真的不太确定。",
    "唔……想不起来了。",
    "我记不太清。",
]

SAFE_REPLY = SAFE_REPLIES[0]


def pick_safe_reply():
    return random.choice(SAFE_REPLIES)