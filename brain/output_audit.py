"""输出审计 - 检测编造嫌疑，返回修正建议

2026-09-30 强化：
- 原正则太死（"我遇到"必须字面连续，导致"最近我在路上遇到了一只小猫"漏网）
- 新正则允许中间插入字符，覆盖更多编造场景
- 新增"学/画/看/帮它/移动"等动作编造检测
- SAFE_REPLY 改成陈述句（原来是反问，加剧"她总反问"的印象）
- 新增 pick_safe_reply() 供调用方随机选一个
"""
import re
import random


_FABRICATION_PATTERNS = [
    # ── 时间指代 + 第一人称经历（放宽：允许"最近/今天/刚才"，允许中间插话）──
    (r"(上次|之前|那次|昨天|前几天|上周|最近|今天|刚才|前些天|这几天|这些天)"
     r".{0,12}(我|咱|我们)"
     r".{0,6}(在|去|到|遇到|看到|听到|闻到|碰到|经过|路过|走|跑)",
     "时间指代编造"),

    # ── 地点编造 ──
    (r"我(在|去了|到了|路过|经过).{1,10}"
     r"(公园|外面|街上|咖啡厅|商场|学校|公司|夜市|医院|海边|山上|楼下|门口|路边)",
     "地点编造"),

    # ── 感知编造（宽松：我{0,6}(遇到|看到|听到|闻到|碰到)）──
    (r"我.{0,6}(遇到|看到|听到|闻到|碰到|遇见|碰见)",
     "感知编造"),

    # ── 童年/过往 ──
    (r"我(们)?(小时候|上学|工作|上班|读书|童年|长大)",
     "过往编造"),

    # ── 环境编造（她没有感官）──
    (r"我(感觉)?(天气|窗外|阳光|下雨|下雪|树叶|天空|云|月亮|星星|外面)",
     "环境编造"),

    # ── 学习/知识编造（放宽：无"我"也算，间隔放宽到 10 字）──
    (r"(我|最近|今天|刚才|这几天)?.{0,4}(学会|学到|学了).{0,10}"
     r"(东西|知识|编程|画画|画|歌|语言|技能|技巧|小说|Python|python|新东西|新的东西)",
     "学习编造"),
    (r"(我|最近|今天|刚才|这几天)?.{0,4}(在学|正在学|最近学|开始学)",
     "学习编造"),

    # ── 画画编造（放宽前缀）──
    (r"(我|最近|今天|刚才|这几天)?.{0,4}(在画|喜欢画|最近画|画了)",
     "画画编造"),

    # ── 阅读/视听编造（放宽前缀）──
    (r"(我|最近|今天|刚才|这几天)?.{0,4}(在看|喜欢看|看了本|看了部|读了|听了)",
     "阅读编造"),

    # ── 主动行动编造（她没身体，不能"帮它找""救""捡"）──
    (r"我(帮它|帮它找|帮它找到|救了|收养了|抱了|捡了|捡到了)",
     "行动编造"),

    # ── 身体移动 ──
    (r"我(走|跑|去到|来到|到达|步行)了.{0,6}",
     "移动编造"),

    # ── 未来邀请（她没身体，"一起去"是编造）──
    (r"(我|咱)们(一起|俩).{0,4}(去|来|看|玩|走)",
     "未来邀请编造"),
]


def audit_output(text):
    """返回 (是否可疑, 命中原因列表)"""
    if not text:
        return False, []
    hits = []
    for pat, reason in _FABRICATION_PATTERNS:
        if re.search(pat, text):
            hits.append(reason)
    return (len(hits) > 0, hits)


# 多选一，避免每次都是同一句
SAFE_REPLIES = [
    "唔……我好像想不起来了。",
    "记不清了。",
    "这个我真的不太确定。",
    "唔……想不起来了。",
    "我记不太清。",
]

# 向后兼容：老调用方仍可以用 SAFE_REPLY
SAFE_REPLY = SAFE_REPLIES[0]


def pick_safe_reply():
    """随机挑一个安全回复"""
    return random.choice(SAFE_REPLIES)