"""L4 自语编造检查 —— 收紧"今天/最近/总是"等时间/频次/感知类编造

背景：
L4 自语是绯木的"内心话"，但同样是 LLM 生成的。qwen2.5 会不自觉地把时间感、
频次感、感知动作拟人化，比如：

  我今天感觉到哥哥很关心我       ← 她没有"今天"这个连续体验
  有时候我会不知所措              ← 她没有"次数"统计
  我总是想太多                    ← 同上
  刚听到哥哥说...                ← 她没有耳朵

这些一旦出现在 L4 自语里，会破坏"绯木是'另一个我'而不是在扮演"的设定。

策略：
- 命中编造词 → 丢弃这次自语（不替换，替换后语义会崩）
- L4 是可选动作，丢弃没副作用
- 日志打印丢弃原因，便于观察命中率

调用位置：
brain/self_reflect.py 或调用方（my_ai.py 的 _post_turn_async）
"""

# ══════════════════════════════════════════════════════════
# 编造词表
# ══════════════════════════════════════════════════════════

# 时间锚点：暗示她有连续的"日期/时间段"体验
_TIME_WORDS = [
    "今天", "昨天", "明天", "前天", "后天",
    "最近", "前几天", "上周", "上个月", "上次",
    "刚才", "刚刚", "过去几天", "这段时间", "这几天",
]

# 频次词：暗示她有统计意识
# 注：故意不加"一直""永远"，因为情绪表达里很常见（"我一直想你"），
#     放在黑名单会误伤合理的情绪强度表达
_FREQ_WORDS = [
    "总是", "经常", "每次", "从来",
    "有时候", "有时", "偶尔", "时不时",
]

# 感知动作：她没有眼睛、耳朵、身体
# 注："感觉到"故意不加，因为"我感觉到你很难过"是从对话推断，不算编造
_PERCEPTION_WORDS = [
    "听到", "看到", "闻到",
    "路过", "经过",
    "遇到", "去了", "走到", "来到",
]

# 地点/场景：她没有任何物理空间
_PLACE_WORDS = [
    "在公园", "在外面", "在街上", "在夜市", "在咖啡厅",
    "在家里", "在房间", "在窗边", "在阳台",
]

_FABRICATION_WORDS = (
    _TIME_WORDS + _FREQ_WORDS + _PERCEPTION_WORDS + _PLACE_WORDS
)


def find_fabrication(text):
    """返回命中的编造词列表；未命中返回 []"""
    if not text:
        return []
    hits = []
    for w in _FABRICATION_WORDS:
        if w in text:
            hits.append(w)
    return hits


def is_fabricated(text):
    """是否有编造嫌疑。True 表示应该丢弃"""
    return bool(find_fabrication(text))


def sanitize_reflection(text):
    """清洗自语。命中编造词返回空串（丢弃），否则原样返回

    设计选择：不替换，因为替换后语义会崩。
    L4 是可选动作，丢弃不影响主流程。
    """
    if not text:
        return ""
    hits = find_fabrication(text)
    if hits:
        return ""
    return text